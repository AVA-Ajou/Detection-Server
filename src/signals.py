#!/usr/bin/env python3
"""전사본에서 사기 진행 단계를 읽는다. 모델을 쓰지 않는다.

**왜 규칙인가** — 전에는 원본 Gemma에게 "1~4 중 몇 단계냐"를 생성으로 물었다. 근거 인용은
정확한데 숫자만 한쪽으로 쏠렸다(거의 전부 2~3). 4택 분류를 자유 생성으로 시킨 셈이라,
확률을 생성으로 뽑지 않기로 한 결정과 같은 함정에 다른 이름으로 들어가 있었다.

**왜 탐지에서는 실패한 정규식이 단계에서는 통하는가** — 사기범은 "검찰"이라는 말을 피하고도
사칭할 수 있다. 그래서 탐지를 정규식으로 하면 뚫린다(실측 43건). 그런데 돈을 받으려면
**결국 계좌를 불러주고 입금하라고 말해야 한다.** 그 말을 피하면 사기가 성립하지 않는다.
탐지는 어댑터가 하고, 단계만 여기서 읽는다.

**요구 문형을 함께 요구한다.** 키워드만 보면 서술문에 헛짚는다.

    "계좌번호나 비밀번호 이런 거 절대 요구할 수가 없게 돼 있고"
        → 사기범이 "우리는 안 물어본다"고 말하는 중인데 정보 요구로 잡힌다

    피싱 706건 / 정상 711건에서 잰 값
        키워드만            81건 / 7건
        요구 문형까지       46건 / 1건   ← 헛짚음이 7분의 1

`../Voice-Detection/calibrate.py` 의 `FEATURES` 에서 출발했지만 **복사본이 아니다.**
저쪽은 신호별 배점(로그 우도비)을 산출하는 도구이고 이쪽은 단계를 판정한다. 목적이 달라서
갈라져도 된다 — 한쪽을 고칠 때 다른 쪽을 따라 고칠 필요가 없다.
"""

import re

STAGES = {
    1: "압박·유인",
    2: "정보·계좌",
    3: "이체 지시",
}

# 지시 문형. 사기범이 **무언가를 시키는** 말투다. 서술("~했습니다")과 가르는 것이 목적이다.
#
# 맨 `하세요`는 일부러 뺐다 — "이전과 동일하게 입금 출금하시고 카드 사용하시고 똑같이 사용
# 가능하세요" 처럼 **안심시키는 서술**까지 이체 지시로 잡혔다. 실측으로 확인한 오발화다.
_DEMAND = (r"(?:주세요|주시겠|주시면|주시죠|주셔야|주시기|해\s*주|불러|알려|보내|말씀\s*해|"
           r"말씀\s*부탁|기재하|입력|누르시|누르세|하십시오|해야\s*되|해야\s*돼|있으셔야|"
           r"있어야|가세요|이동하십|오셔야|오시면|진술해|부탁드|찍어|확인해\s*주)")

# 질문 문형. **정보는 시키지 않고 물어서도 빼낸다** — "잔액이 얼마씩 남으셨죠?" 는 요구다.
# 돈은 물어보는 것만으로 움직이지 않으므로 3단계에는 쓰지 않는다.
_ASK = r"(?:십니까|시나요|신가요|셨나요|으셨|어떻게 되|얼마|몇 개)"

# 키워드와 뒤따르는 문형 사이에 끼어드는 말이 이 길이를 넘으면 같은 요구로 보지 않는다.
_GAP = r".{0,30}?"


def _demanded(keyword):
    """키워드 뒤 가까운 곳에 **지시** 문형이 와야 성립한다. 돈을 움직이는 신호에 쓴다."""
    return f"(?:{keyword}){_GAP}{_DEMAND}"


def _asked(keyword):
    """지시뿐 아니라 **질문**도 요구로 본다. 정보를 캐내는 신호에 쓴다."""
    return f"(?:{keyword}){_GAP}(?:{_DEMAND}|{_ASK})"


# (단계, 이름, 패턴). 단계가 높을수록 사기가 진행된 것이다.
#
# 1단계는 요구 문형을 붙이지 않는다 — 겁을 주는 말은 원래 서술문이라("구속영장이 발부됩니다")
# 요구 문형을 요구하면 거의 잡히지 않는다.
SIGNALS = [
    (1, "CRIMINAL_INVOLVEMENT", r"명의\s*도용|명의가 도용|도용되|대포\s*통장|공범|연루|"
                                r"가해자|피해자 입증|금융\s*범죄|금융\s*사기"),
    (1, "FEAR_PRESSURE", r"구속|영장|처벌|동결|압수|소환장?|위증죄|지급\s*정지|거래\s*정지|"
                         r"금융\s*제한|법적 조치"),
    (1, "LOAN_OFFER", r"대출|대환|저금리|정부\s*지원|정부지원|정책\s*자금|서민\s*금융|햇살론|"
                      r"보증서|한도\s*조회"),
    (1, "URGENCY", r"지금 바로|오늘까지|오늘 안|즉시|서둘|마감|소진"),
    (1, "SECRECY", r"말하지 마|알리지 마|비밀로|말씀하지 마|얘기하지 마|제3자|유출하실 경우"),
    (1, "STAY_ON_LINE", r"끊지 마|끊으시면 안|전화 끊"),

    (2, "PERSONAL_INFO", _asked(r"주민\s*등록\s*번호|주민\s*번호|비밀\s*번호|카드\s*번호|"
                                r"보안\s*카드|OTP|생년월일|성함|등초본|등본|초본|"
                                r"신분증\s*사본|재직\s*증명")),
    (2, "ACCOUNT_INFO", _asked(r"계좌\s*번호|잔액|금액|입출금|예치|주거래\s*은행|"
                               r"금융권.{0,8}상호|은행권.{0,8}(?:명칭|상호)|유동성 자금")),
    (2, "REMOTE_CONTROL", _asked(r"앱\s*설치|어플|다운로드|원격|링크|주소로 들어|접속하|"
                                 r"홈페이지 주소|데이터 차단|와이파이 차단|신고 센터|"
                                 r"실명\s*확인")),

    (3, "TRANSFER_DEMAND", _demanded(r"이체|송금|입금|계좌로 보내|돈을 보내|현찰 찾|현금.{0,4}찾|"
                                     r"인출|은행으로")),
    (3, "REPAY_FIRST", _demanded(r"기존.{0,10}대출|먼저.{0,6}상환|중도\s*상환|완납|납부\s*처리|"
                                 r"은행 업무를 다 보")),
    (3, "UPFRONT_FEE", _demanded(r"수수료|보증금|보증\s*보험|예치금|선입금|합의금|합의\s*금액|"
                                 r"비용을 부담")),
    (3, "HANDOVER", _demanded(r"계좌를? 빌려|통장을? 빌려|계좌 임대|체크\s*카드를? 보내|"
                              r"카드 들고|만나서")),
]

_COMPILED = [(stage, name, re.compile(pat)) for stage, name, pat in SIGNALS]

# 인용구를 뜯을 때 앞뒤로 붙이는 여유. 화면에 한 줄로 나가므로 짧게 잡는다.
_LEAD, _TRAIL = 18, 12


def _quote(text, match):
    start = max(0, match.start() - _LEAD)
    end = min(len(text), match.end() + _TRAIL)
    return ("…" if start else "") + text[start:end].strip() + ("…" if end < len(text) else "")


def fired(text):
    """발동한 신호를 (단계, 이름, 인용구)로 돌려준다. 없으면 빈 목록."""
    out = []
    for stage, name, pattern in _COMPILED:
        m = pattern.search(text)
        if m:
            out.append((stage, name, _quote(text, m)))
    return out


def stage_of(text):
    """(단계, 근거 목록). 발동한 신호 중 **가장 높은 단계**를 쓴다 — 사기는 되돌아가지 않는다.

    아무것도 안 잡히면 `(None, [])`. **이때 1단계로 올려 찍지 않는다.** 증거 없이 단계를
    붙이는 건 생성 모델이 하던 실수와 같다. 피싱 706건 중 약 15%가 여기 해당한다.
    """
    signals = fired(text)
    if not signals:
        return None, []
    top = max(s for s, _, _ in signals)
    return top, [(n, q) for s, n, q in signals if s == top]


def label(stage):
    return STAGES.get(stage)


if __name__ == "__main__":
    import sys
    text = sys.stdin.read()
    stage, evidence = stage_of(text)
    print(f"단계 {stage} {label(stage) or '(판단 불가)'}")
    for name, quote in evidence:
        print(f"  {name:18} {quote}")
