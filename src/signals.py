_COMPILED = [(stage, name, re.compile(pat)) for stage, name, pat in SIGNALS]

# 인용구를 뜯을 때 앞뒤로 붙이는 여유. 화면에 한 줄로 나가므로 짧게 잡는다.
_LEAD, _TRAIL = 18, 12


def _quote(text, match):
    start = max(0, match.start() - _LEAD)
    end = min(len(text), match.end() + _TRAIL)
    return ("…" if start else "") + text[start:end].strip() + ("…" if end < len(text) else "")


def fired(text):
    """발동한 신호를 (단계, 이름, 인용구)로 돌려준다. 없으면 빈 목록."""
    out = []
    for stage, name, pattern in _COMPILED:
        m = pattern.search(text)
        if m:
            out.append((stage, name, _quote(text, m)))
    return out


def stage_of(text):
    """(단계, 근거 목록). 발동한 신호 중 **가장 높은 단계**를 쓴다 — 사기는 되돌아가지 않는다.

    아무것도 안 잡히면 `(None, [])`. **이때 1단계로 올려 찍지 않는다.** 증거 없이 단계를
    붙이는 건 생성 모델이 하던 실수와 같다. 피싱 706건 중 약 15%가 여기 해당한다.
    """
    signals = fired(text)
    if not signals:
        return None, []
    top = max(s for s, _, _ in signals)
    return top, [(n, q) for s, n, q in signals if s == top]


def label(stage):
    return STAGES.get(stage)


